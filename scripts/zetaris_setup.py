#!/usr/bin/env python3
"""Register Parallax's SEC EDGAR sources in your Zetaris instance, then verify them.

  backend/.venv/bin/python scripts/zetaris_setup.py --write-sql          # write zetaris/sql/*.sql only
  backend/.venv/bin/python scripts/zetaris_setup.py --dry-run            # show the plan, send nothing
  backend/.venv/bin/python scripts/zetaris_setup.py --apply              # create objects + verify
  backend/.venv/bin/python scripts/zetaris_setup.py --apply --tickers AAPL TSLA --skip-existing
  backend/.venv/bin/python scripts/zetaris_setup.py --verify             # re-run verification only

Steps (mirroring Zetaris's own EDGAR recipe and its verification advice):
 1. Probe the direct SEC API to find which concepts each company actually reports (so no REST
    table points at a 404).
 2. CREATE LIGHTNING DATABASE, CREATE SCHEMASTORE CONTAINER, then one CREATE LIGHTNING REST
    TABLE + CREATE SCHEMASTORE VIEW per company/concept, one statement per request.
 3. Verify: SELECT COUNT(*) from each view and compare with the direct SEC row count.
 4. Write zetaris/registered_views.json, which the backend reads in FINSIGHT_DATA_MODE=zetaris.

Create statements change your Zetaris instance; review --dry-run output first.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.config import get_settings  # noqa: E402
from app.financial_data.companies import LIVE_COMPANIES, METRICS, find_company  # noqa: E402
from app.financial_data.sec_client import SecClient  # noqa: E402
from app.integrations.zetaris.client import ZetarisClient, ZetarisError  # noqa: E402
from app.integrations.zetaris.registry import MANIFEST, load_manifest, merge_manifest  # noqa: E402
from app.integrations.zetaris.sql import ViewSpec, container_sql, database_sql, rest_table_sql, view_sql  # noqa: E402

SQL_FILE = ROOT / "zetaris" / "sql" / "finsight_edgar_create.sql"
PLACEHOLDER_UA = "YOUR_APP_NAME YOUR_CONTACT_EMAIL"


def all_specs(tickers: list[str] | None) -> list[ViewSpec]:
    if tickers:  # any SEC-listed ticker, not only the built-in companies
        comps = [c for c in (find_company(t) for t in tickers) if c is not None and not c.sample]
        missing = sorted(set(tickers) - {c.ticker for c in comps})
        if missing:
            print(f"Not SEC-listed (skipped): {', '.join(missing)}")
    else:
        comps = list(LIVE_COMPANIES)
    return [ViewSpec(c, m, t) for c in comps for m in METRICS for t in m.tags]


def write_sql_file(specs: list[ViewSpec], db: str, container: str) -> None:
    lines = [
        "-- Parallax: SEC EDGAR XBRL companyconcept sources for Zetaris Lightning.",
        "-- Generated by scripts/zetaris_setup.py --write-sql. Pattern copied from Zetaris's verified recipe",
        "-- getting-started/open_data/rest_apis/sql/rate_limited/01_edgar_company_facts_create.sql.",
        f"-- Replace {PLACEHOLDER_UA} with your own 'app_name contact@email' (SEC requires it).",
        "-- Run ONE statement at a time in the SQL Editor; some companies do not report every concept",
        "-- (their REST tables return 404) - scripts/zetaris_setup.py --apply skips those automatically.",
        "-- CREATE SCHEMASTORE CONTAINER has no IF NOT EXISTS; comment it out if it already exists.",
        "",
        database_sql(db) + ";",
        "",
        container_sql(container) + ";",
        "",
    ]
    for s in specs:
        lines += [f"-- {s.company.name} ({s.company.ticker}) {s.metric.label}: us-gaap:{s.tag}",
                  rest_table_sql(s, db, PLACEHOLDER_UA) + ";", "", view_sql(s, db, container) + ";", ""]
    SQL_FILE.parent.mkdir(parents=True, exist_ok=True)
    SQL_FILE.write_text("\n".join(lines))
    print(f"wrote {SQL_FILE.relative_to(ROOT)} ({len(specs)} company/concept pairs)")


API_EMPTY: dict[tuple[str, str], int] = {}  # companyconcept empty, companyfacts has rows


async def probe(specs: list[ViewSpec], sec: SecClient) -> dict[tuple[str, str], int]:
    counts: dict[tuple[str, str], int] = {}
    for s in specs:
        r = await sec.concept_rows(s.company.cik, s.tag)
        key = (s.company.ticker, s.tag)
        if r.get("fallback") == "companyfacts":
            counts[key] = 0  # a Zetaris REST table on companyconcept would be empty: don't register it
            API_EMPTY[key] = len(r["rows"])
        else:
            counts[key] = len(r["rows"])
    return counts


async def run_statement(z: ZetarisClient, sql: str, skip_existing: bool) -> str:
    try:
        await z.run_query(sql, limit=1)
        return "ok"
    except ZetarisError as exc:
        if skip_existing and "exist" in str(exc).lower():
            return "exists"
        raise


async def verify(z: ZetarisClient, specs: list[ViewSpec], expected: dict[tuple[str, str], int], container: str) -> list[dict]:
    rows = []
    for s in specs:
        sql = f"SELECT COUNT(*) AS n FROM {container}.{s.view}"
        try:
            q = await z.run_query(sql, limit=1)
            n = int(next(iter(q.rows[0].values()))) if q.rows else 0
            err = None
        except (ZetarisError, ValueError, StopIteration) as exc:
            n, err = None, str(exc)
        exp = expected.get((s.company.ticker, s.tag))
        rows.append({"ticker": s.company.ticker, "metric": s.metric.key, "tag": s.tag, "view": s.view,
                     "zetaris_rows": n, "sec_rows": exp, "match": n == exp, "error": err})
        print(f"  {s.view:40s} zetaris={n} sec={exp} {'OK' if n == exp else 'MISMATCH'}{' ' + err if err else ''}")
    return rows


async def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write-sql", action="store_true")
    g.add_argument("--dry-run", action="store_true")
    g.add_argument("--apply", action="store_true")
    g.add_argument("--verify", action="store_true")
    ap.add_argument("--tickers", nargs="*")
    ap.add_argument("--skip-existing", action="store_true", help="treat 'already exists' errors as success")
    args = ap.parse_args()

    s = get_settings()
    db, container = s.zetaris_lightning_db, s.zetaris_container
    specs = all_specs([t.upper() for t in args.tickers] if args.tickers else None)
    if args.write_sql:
        write_sql_file(specs, db, container)
        return 0

    ua = s.sec_user_agent
    if not ua or "@" not in ua:
        print("Set SEC_USER_AGENT (or ZETARIS_USER_AGENT) to 'app_name contact@email' first.", file=sys.stderr)
        return 2
    z = ZetarisClient(s)
    problems = z.configuration_problems()
    if problems and not args.dry_run:
        print("Zetaris is not configured: " + "; ".join(problems), file=sys.stderr)
        return 2
    sec = SecClient(ua, s.cache_dir)
    print("Probing SEC for the concepts each company reports...")
    counts = await probe(specs, sec)
    present = [sp for sp in specs if counts[(sp.company.ticker, sp.tag)] > 0]
    print(f"{len(present)} of {len(specs)} company/concept pairs have data.")

    if args.dry_run:
        print(f"\n{database_sql(db)};\n{container_sql(container)};")
        for sp in present:
            print(f"\n-- {sp.company.ticker} {sp.tag} ({counts[(sp.company.ticker, sp.tag)]} SEC rows)\n"
                  f"{rest_table_sql(sp, db, ua)};\n{view_sql(sp, db, container)};")
        print("\nDry run only: nothing was sent to Zetaris.")
        return 0

    dbs, req_id, _ = await z.list_databases()
    print(f"Zetaris reachable: {len(dbs)} Lightning databases visible (request {req_id}).")

    if args.apply:
        for label, sql in (("database", database_sql(db)), ("container", container_sql(container))):
            print(f"{label}: {await run_statement(z, sql, True)}")
        for sp in present:
            for kind, sql in (("rest table", rest_table_sql(sp, db, ua)), ("view", view_sql(sp, db, container))):
                status = await run_statement(z, sql, args.skip_existing)
                print(f"  {sp.company.ticker:5s} {sp.tag:58s} {kind}: {status}")
                await asyncio.sleep(0.2)

    print("Verifying row counts against the direct SEC API...")
    rows = await verify(z, present, counts, container)
    good = [r for r in rows if r["match"]]
    no_data = [{"ticker": sp.company.ticker, "metric": sp.metric.key, "tag": sp.tag}
               for sp in specs if counts[(sp.company.ticker, sp.tag)] == 0 and (sp.company.ticker, sp.tag) not in API_EMPTY]
    api_empty = [{"ticker": sp.company.ticker, "metric": sp.metric.key, "tag": sp.tag,
                  "companyfacts_rows": API_EMPTY[(sp.company.ticker, sp.tag)]}
                 for sp in specs if (sp.company.ticker, sp.tag) in API_EMPTY]
    if api_empty:
        print(f"SEC companyconcept returns no rows for {len(api_empty)} pair(s) that companyfacts has; "
              f"Parallax reads those from SEC directly: " + ", ".join(f"{v['ticker']}:{v['tag']}" for v in api_empty))
    merged = merge_manifest(load_manifest(), db=db, container=container, base_url=s.zetaris_base_url,
                            probed=[(sp.company.ticker, sp.tag) for sp in specs], verified=good,
                            rejected=[r for r in rows if not r["match"]], no_data=no_data, api_empty=api_empty)
    MANIFEST.write_text(json.dumps(merged, indent=2) + "\n")
    print(f"{len(good)} of {len(rows)} views verified this run; manifest now lists {len(merged['views'])} views "
          f"({len({v['ticker'] for v in merged['views']})} companies) in {MANIFEST.relative_to(ROOT)}.")
    return 0 if good else 1


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
